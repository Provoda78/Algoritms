/*
Задание (3):
1) Изучить работу программы.
2) Написать программу,
	выводящую числа от 0 до 100 в один ряд через ','
*/

#include <iostream>

int main()
{
	int grad = 100;

	for (int i = 0; i < grad; i++)
	{
		std::cout << i << ", ";
	}

	std::cout << grad << "." << std::endl;
}
